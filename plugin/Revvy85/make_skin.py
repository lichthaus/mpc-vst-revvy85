#!/usr/bin/env python3
"""make_skin.py - draws the Revvy85 plugin skin: a PANEL page laid out like the unit's front panel
(display window, knob row, key blocks) and the LEVELS page from ui.json.

PANEL page (1280 x 628):
  - the 2 x 16 LCD as 32 image cells, each a 256-frame character strip bound to an "LCD n"
    parameter (the MPC redraws an image when its parameter moves);
  - the two red memory digits: 128-frame strips drawn segment by segment from the LED byte
    (bit 0 g, 1 a, 2 f, 3 b, 4 d, 5 e, 6 c; checked against programs 1-6 and 9), in one focusable
    component: touch it and turn the data wheel to pick a memory, push the wheel or double-tap to
    recall it;
  - the input meter (9 frames) and the MONO / BP indicators;
  - the key LEDs: one 256-frame strip per LED (lit when its bit of "LEDs n" is set);
  - the knob row (Input Level, the EQ, Mixing, Volume; touch a knob, then turn the data wheel) and
    the MONO and EQ switches;
  - every key as an image button (a tap flips its parameter, which the plugin turns into one press).

Output: skins/ (TUI.json, Q-Links.json, images; git-ignored, regenerated by make.sh). Nothing here
comes from the firmware.

Run after one build (it reads build/params.json), then build again:
  uv run --with pillow python3 make_skin.py && python3 "$MPC_SDK/tools/build.py" .
"""
