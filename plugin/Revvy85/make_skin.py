def font(path, size, index=0):
    try:
        return ImageFont.truetype(path, size, index=index)
    except OSError:
        return ImageFont.load_default()


def centred(d, box, text, f, fill):
    x0, y0, x1, y1 = box
    b = d.textbbox((0, 0), text, font=f)
    d.text(((x0 + x1 - (b[2] - b[0])) / 2 - b[0], (y0 + y1 - (b[3] - b[1])) / 2 - b[1]), text, font=f, fill=fill)


# ---- images ----
def char_strip(path):
    f = font(MENLO, 38, index=1)
    strip = Image.new("RGB", (CELL_W, CELL_H * 256), LCD_GLASS)
    d = ImageDraw.Draw(strip)
    for frame in range(256):
        y0 = frame * CELL_H
        if frame < 0x20 or frame >= 0x80:
            if frame != 0x20 and frame < 0x10 or frame >= 0x80:       # unknown codes: a dim dot block
                for y in range(8):
                    for x in range(5):
                        if (x + y) % 2 == 0:
                            d.rectangle([3 + x * 4.6, y0 + 4 + y * 4.8, 6 + x * 4.6, y0 + 7 + y * 4.8], fill=(0xB8, 0xB3, 0x30))
            continue
        ch = {0x5C: "¥", 0x7E: "→", 0x7F: "←"}.get(frame, chr(frame))
        if ch == " ":
            continue
        b = d.textbbox((0, 0), ch, font=f)
        d.text(((CELL_W - (b[2] - b[0])) / 2 - b[0], y0 + (CELL_H - 38) / 2 - 4), ch, font=f, fill=LCD_INK)
    strip.save(path, optimize=True)


def segment_polys(w, h):
    """Seven slanted segments in a w x h box: bit 0 g, 1 a, 2 f, 3 b, 4 d, 5 e, 6 c."""
    t, slant, m = 9, 0.12, 6

    def P(x, y):
        return (x + (h - y) * slant, y)
    L, R, T, B, M = m, w - m - h * slant, m, h - m, h / 2
    hs = lambda y: [P(L + t * 0.6, y), P(L + t, y - t / 2), P(R - t, y - t / 2), P(R - t * 0.6, y), P(R - t, y + t / 2), P(L + t, y + t / 2)]
    vs = lambda x, y0, y1: [P(x, y0 + t * 0.6), P(x + t / 2, y0 + t), P(x + t / 2, y1 - t), P(x, y1 - t * 0.6), P(x - t / 2, y1 - t), P(x - t / 2, y0 + t)]
    return {0: hs(M), 1: hs(T + t / 2), 2: vs(L + t / 2, T + t / 2, M), 3: vs(R - t / 2, T + t / 2, M),
            4: hs(B - t / 2), 5: vs(L + t / 2, M, B - t / 2), 6: vs(R - t / 2, M, B - t / 2)}


def digit_strip(path):
    ss = 3
    polys = segment_polys(DIGIT_W * ss, DIGIT_H * ss)
    strip = Image.new("RGB", (DIGIT_W, DIGIT_H * 128), WINDOW)
    for frame in range(128):
        big = Image.new("RGB", (DIGIT_W * ss, DIGIT_H * ss), WINDOW)
        d = ImageDraw.Draw(big)
        for bit, poly in polys.items():
            d.polygon(poly, fill=RED_ON if frame & (1 << bit) else RED_OFF)
        strip.paste(big.resize((DIGIT_W, DIGIT_H), Image.LANCZOS), (0, frame * DIGIT_H))
    strip.save(path, optimize=True)


def meter_strip(path):
    w, h = METER[2], METER[3]
    seg_h = h // 8
    strip = Image.new("RGB", (w, h * 9), WINDOW)
    d = ImageDraw.Draw(strip)
    for frame in range(9):
        for k in range(8):                          # k 0 = bottom (-30) ... 7 = top (CLIP)
            on = k < frame
            red = k >= 4
            col = (RED_ON if red else GREEN_ON) if on else (RED_OFF if red else GREEN_OFF)
            y = frame * h + (7 - k) * seg_h
            d.rectangle([2, y + 3, w - 3, y + seg_h - 3], fill=col)
    strip.save(path, optimize=True)


def indicator_strip(path, text):
    strip = Image.new("RGB", (IND_W, IND_H * 2), WINDOW)
    d = ImageDraw.Draw(strip)
    f = font(SANS, 24, index=1)
    for frame, col in enumerate([RED_OFF, RED_ON]):
        centred(d, (0, frame * IND_H, IND_W, (frame + 1) * IND_H), text, f, col)
    strip.save(path, optimize=True)


def lamp_strip(path, bit):
    strip = Image.new("RGBA", (LAMP_W, LAMP_H * 256), (0, 0, 0, 0))
    d = ImageDraw.Draw(strip)
    for frame in range(256):
        col = RED_ON if frame & (1 << bit) else RED_OFF
        d.rounded_rectangle([0, frame * LAMP_H, LAMP_W - 1, frame * LAMP_H + LAMP_H - 1], radius=2, fill=col)
    strip.save(path, optimize=True)


def knob_strip(path):
    ss = 4
    s = KNOB * ss
    strip = Image.new("RGBA", (KNOB, KNOB * KNOB_FRAMES), (0, 0, 0, 0))
    for i in range(KNOB_FRAMES):
        big = Image.new("RGBA", (s, s), (0, 0, 0, 0))
        d = ImageDraw.Draw(big)
        c = s / 2
        for k in range(11):                         # scale ticks, 300 degrees
            a = math.radians(120 + k * 30)
            d.line([(c + math.cos(a) * s * 0.40, c + math.sin(a) * s * 0.40), (c + math.cos(a) * s * 0.48, c + math.sin(a) * s * 0.48)],
                   fill=(0xC8, 0xC8, 0xC8, 255), width=ss * 2)
        r = s * 0.34
        d.ellipse([c - r, c - r, c + r, c + r], fill=(0x0E, 0x0E, 0x10, 255), outline=(0x3A, 0x3B, 0x3F, 255), width=ss * 2)
        for k in range(24):                         # knurling
            a = 2 * math.pi * k / 24
            d.line([(c + math.cos(a) * r * 0.82, c + math.sin(a) * r * 0.82), (c + math.cos(a) * r * 0.97, c + math.sin(a) * r * 0.97)],
                   fill=(0x24, 0x25, 0x28, 255), width=ss)
        a = math.radians(120 + 300 * i / (KNOB_FRAMES - 1))
        d.line([(c + math.cos(a) * r * 0.15, c + math.sin(a) * r * 0.15), (c + math.cos(a) * r * 0.9, c + math.sin(a) * r * 0.9)],
               fill=(0xF4, 0xF4, 0xF4, 255), width=ss * 3)
        strip.paste(big.resize((KNOB, KNOB), Image.LANCZOS), (0, i * KNOB))
    strip.save(path, optimize=True)


def switch_image(path, pressed):
    ss = 3
    img = Image.new("RGBA", (SWITCH * ss, SWITCH * ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rectangle([2 * ss, 2 * ss, (SWITCH - 2) * ss, (SWITCH - 2) * ss], fill=(0x08, 0x08, 0x09), outline=(0x40, 0x41, 0x45), width=2 * ss)
    inset = 12 if pressed else 7
    face = (0x9A, 0x9B, 0x9E) if pressed else (0x50, 0x51, 0x55)
    d.rectangle([inset * ss, inset * ss, (SWITCH - inset) * ss, (SWITCH - inset) * ss], fill=face)
    img.resize((SWITCH, SWITCH), Image.LANCZOS).save(path, optimize=True)


def key_image(path, caption, w, h, face):
    ss = 3
    img = Image.new("RGBA", (w * ss, h * ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([1 * ss, 1 * ss, (w - 1) * ss, (h - 1) * ss], radius=4 * ss, fill=face, outline=KEY_EDGE, width=2 * ss)
    col = KEY_GOLD if caption in ("CLEAR", "ENTER") else TEXT
    words = caption.split(" ")
    if len(caption) == 1:
        f = font(SANS, 30 * ss, index=1)
        centred(d, (0, 0, w * ss, h * ss), caption, f, col)
    elif len(words) == 2 and len(caption) > 8:
        f = font(SANS, 13 * ss, index=1)
        centred(d, (0, 2 * ss, w * ss, h * ss / 2 + 2 * ss), words[0], f, col)
        centred(d, (0, h * ss / 2 - 2 * ss, w * ss, (h - 2) * ss), words[1], f, col)
    else:
        f = font(SANS, (17 if len(caption) <= 6 else 14) * ss, index=1)
        centred(d, (0, 0, w * ss, h * ss), caption, f, col)
    img.resize((w, h), Image.LANCZOS).save(path, optimize=True)


def background(path):
    img = Image.new("RGB", (W, H), PANEL)
    d = ImageDraw.Draw(img)
    x, y, w, h = WIN
    d.rounded_rectangle([x, y, x + w, y + h], radius=8, fill=WINDOW, outline=WINDOW_EDGE, width=2)
    d.text((34, 58), "DIGITAL REVERB", font=font(SANS, 15, index=1), fill=MUTED)
    d.text((32, 80), "REVVY 85", font=font(SANS, 52, index=1), fill=TEXT)
    d.text((34, 150), "runs your own\nV1.0 EPROM", font=font(SANS, 13), fill=DIM, spacing=4)
    mx, my, mw, mh = METER
    for k, lab in enumerate(["CLIP", "0", "-3", "-6", "-10", "-15", "-20", "-30"]):
        d.text((mx + mw + 8, my + k * (mh // 8) + 3), lab, font=font(SANS, 13, index=1), fill=MUTED)
    centred(d, (DIGITS[0][1], DIGIT_Y + DIGIT_H + 8, DIGITS[1][1] + DIGIT_W, DIGIT_Y + DIGIT_H + 30), "MEMORY", font(SANS, 15, index=1), MUTED)
    lx, ly, lw, lh = LCD
    d.rounded_rectangle([lx, ly, lx + lw, ly + lh], radius=6, fill=LCD_BEZEL)
    d.rectangle([lx + 8, ly + 8, lx + lw - 8, ly + lh - 8], fill=LCD_GLASS)
    # knob row captions
    small, tiny = font(SANS, 14, index=1), font(SANS, 12, index=1)
    for name, cap, cx, kind in CONTROLS:
        centred(d, (cx - 60, 252, cx + 60, 268), cap, small, MUTED)
    for lab, a, b in GROUPS:
        d.line([(a - 30, 244), (b + 30, 244)], fill=DIM, width=1)
        centred(d, ((a + b) / 2 - 24, 234, (a + b) / 2 + 24, 252), lab, small, MUTED)
        d.rectangle([(a + b) / 2 - 36, 236, (a + b) / 2 + 36, 250], fill=PANEL)
        centred(d, ((a + b) / 2 - 36, 236, (a + b) / 2 + 36, 250), lab, small, MUTED)
    d.text((1088, 404), "Tap a key to press it\nonce. Touch a knob,\nthen turn the data\nwheel.\n\nMEMORY: touch, turn\nthe wheel, push it (or\ndouble-tap) to recall.\n\nLEVELS page: program,\nheadroom, stages.", font=font(SANS, 13), fill=DIM, spacing=5)
    img.save(path, optimize=True)


def key_file(name):
    s = name.lower().replace(" ", "").replace("/", "").replace("-", "minus").replace("+", "plus").replace(".", "dot")
    return "%s_key_%s.png" % (PREFIX, s)


def lamp_file(col, bit):
    return "%s_led%d_%d.png" % (PREFIX, col, bit)


def key_box(x, row, w):
    return x, ROWS_Y[row], w, KEY_H


def preview(path):
    img = Image.open(os.path.join(OUT, PREFIX + "_bg.png")).convert("RGBA")

    def frame_of(file, n, fh, fw=None):
        im = Image.open(os.path.join(OUT, file)).convert("RGBA")
        return im.crop((0, n * fh, fw or im.width, (n + 1) * fh))
    chars = Image.open(os.path.join(OUT, PREFIX + "_lcd_chars.png")).convert("RGBA")
    for i, ch in enumerate("   LARGE HALL   " + " REV TIME = 2.6s"):
        cell = chars.crop((0, ord(ch) * CELL_H, CELL_W, (ord(ch) + 1) * CELL_H))
        img.paste(cell, (CELLS_X + (i % 16) * CELL_W, CELLS_Y + (i // 16) * (CELL_H + ROW_GAP)))
    for (name, x), byte in zip(DIGITS, [0x00, 0x48]):
        img.alpha_composite(frame_of(PREFIX + "_digit.png", byte, DIGIT_H), (x, DIGIT_Y))
    img.alpha_composite(frame_of(PREFIX + "_meter.png", 5, METER[3]), METER[:2])
    for name, text, x, y in INDICATORS:
        img.alpha_composite(frame_of("%s_ind_%s.png" % (PREFIX, name.lower().replace(" ", "")), 0, IND_H), (x, y))
    lit = {(3, 0), (4, 1)}
    for name, cap, x, row, w, face, lamp in KEYS:
        bx, by, bw, bh = key_box(x, row, w)
        img.alpha_composite(Image.open(os.path.join(OUT, key_file(name))).convert("RGBA"), (bx, by))
        if lamp:
            img.alpha_composite(frame_of(lamp_file(*lamp), (1 << lamp[1]) if lamp in lit else 0, LAMP_H), (bx + (bw - LAMP_W) // 2, by - 10))
    for name, cap, cx, kind in CONTROLS:
        if kind == "knob":
            img.alpha_composite(frame_of(PREFIX + "_knob.png", {"Mixing": 40, "Volume": 40, "HP Freq": 0, "LP Freq": 63, "SEM Res": 0, "SEM Mode": 0, "SEM Mix": 0}.get(name, 32), KNOB), (cx - KNOB // 2, KNOB_Y))
        else:
            img.alpha_composite(Image.open(os.path.join(OUT, "%s_sw_%s.png" % (PREFIX, "off"))).convert("RGBA"),
                                (cx - SWITCH // 2, KNOB_Y + (KNOB - SWITCH) // 2))
    full = Image.new("RGBA", (1280, 800), (0x10, 0x10, 0x12, 255))
    full.alpha_composite(img, (0, 110))
    full.convert("RGB").save(path)


def fixed_component(children, actions=(), ignore_mouse=False):
    return G.component_definition(list(actions), children, "00000000", ignore_mouse)


def image_strip_def(name, image, frames, w, h):
    e = G.entry(name, "Image", G.obj(("version", 2), ("imageType", "FilmStrip"), ("colour", "0"), ("image", image),
                                     ("numFrames", frames), ("handleName", "Data")),
                "0 0 %d %d" % (w, h), "No", "Show", "Always")
    return fixed_component([e], ignore_mouse=True)


def main():
    if not os.path.isfile(PARAMS):
        sys.exit("make_skin: build once first (needs build/params.json)")
    params = G.load_params(PARAMS)
    table = G.ParamTable(params)
    pages, style, knob_image, frames, kit = G.load_ui(os.path.join(HERE, "ui.json"), table)
    levels = [p for p in pages if p.name == "LEVELS"]
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    kit_dir, kit_assets = G.kit_dir_for(kit, os.path.join(HERE, "build"), OUT)
    tui = G.build_tui(levels, params, style, knob_image, frames, kit_assets)

    char_strip(os.path.join(OUT, PREFIX + "_lcd_chars.png"))
    digit_strip(os.path.join(OUT, PREFIX + "_digit.png"))
    meter_strip(os.path.join(OUT, PREFIX + "_meter.png"))
    knob_strip(os.path.join(OUT, PREFIX + "_knob.png"))
    switch_image(os.path.join(OUT, PREFIX + "_sw_off.png"), False)
    switch_image(os.path.join(OUT, PREFIX + "_sw_on.png"), True)
    for name, text, x, y in INDICATORS:
        indicator_strip(os.path.join(OUT, "%s_ind_%s.png" % (PREFIX, name.lower().replace(" ", ""))), text)
    background(os.path.join(OUT, PREFIX + "_bg.png"))
    lamps = sorted({k[6] for k in KEYS if k[6]})
    for col, bit in lamps:
        lamp_strip(os.path.join(OUT, lamp_file(col, bit)), bit)
    for name, cap, x, row, w, face, lamp in KEYS:
        key_image(os.path.join(OUT, key_file(name)), cap, w, KEY_H, face)

    by = lambda n: table.lookup(n, "make_skin")
    defs, children = [], []
    children.append(G.entry("background", "Image", G.obj(("version", 2), ("imageType", "Regular"), ("colour", "0"), ("image", PREFIX + "_bg.png")),
                            "0 0 %d %d" % (W, H), "No", "Show", "Always"))
    # LCD cells
    defs.append((PREFIX + "Cell", image_strip_def("cell", PREFIX + "_lcd_chars.png", 256, CELL_W, CELL_H)))
    for i in range(32):
        x, y = CELLS_X + (i % 16) * CELL_W, CELLS_Y + (i // 16) * (CELL_H + ROW_GAP)
        children.append(G.entry("lcd %d" % i, PREFIX + "Cell", G.obj(("version", 1), ("handleName", "Data")),
                                "%d %d %d %d" % (x, y, CELL_W, CELL_H), "No", "Show", "Always", remap=[("Data", by("LCD %d" % (i + 1)).handle)]))
    # memory digits, meter, indicators
    # MEMORY digits: one focusable component. Touching it gives Memory Select the data wheel (the plugin
    # shows the number being picked on the digits); a wheel push or a double tap flips Recall Push.
    dx0 = DIGITS[0][1] - 6
    dw = DIGITS[1][1] + DIGIT_W + 6 - dx0
    dig_children = [G.entry("focus", "Focus", G.focus_data(style["accent"]), "0 0 %d %d" % (dw, DIGIT_H + 12), "No", "Show", "WhenFocussed")]
    for (name, x), hn in zip(DIGITS, ("Tens", "Units")):
        dig_children.append(G.entry(name, "Image", G.obj(("version", 2), ("imageType", "FilmStrip"), ("colour", "0"), ("image", PREFIX + "_digit.png"),
                                                          ("numFrames", 128), ("handleName", hn)),
                                    "%d 6 %d %d" % (x - dx0, DIGIT_W, DIGIT_H), "No", "Show", "Always"))
    # an invisible 1 x 1 knob on Memory Select, as the data wheel drives a focused knob (H3000 pattern)
    Image.new("RGBA", (1, 90), (0, 0, 0, 0)).save(os.path.join(OUT, PREFIX + "_blank90.png"))
    dig_children.append(G.entry("wheel", "Knob", G.knob_filmstrip_data(PREFIX + "_blank90.png", 90, "Vertical"), "0 0 1 1", "No", "Show", "Always"))
    # no Q-Link action: touching the digits gives them the data wheel without re-banking the knobs
    dig_actions = [G.action("Enter Pressed", "Toggle Switch", "Push", ""),
                   G.action("Double Click", "Toggle Switch", "Push", "")]
    defs.append((PREFIX + "Memory", fixed_component(dig_children, dig_actions)))
    children.append(G.entry("memory digits", PREFIX + "Memory", G.obj(("version", 1), ("handleName", "Data")),
                            "%d %d %d %d" % (dx0, DIGIT_Y - 6, dw, DIGIT_H + 12), "Yes", "Show", "Always",
                            remap=[("Data", by("Memory Select").handle), ("Push", by("Recall Push").handle),
                                   ("Tens", by("Memory Tens").handle), ("Units", by("Memory Units").handle)]))
    defs.append((PREFIX + "Meter", image_strip_def("meter", PREFIX + "_meter.png", 9, METER[2], METER[3])))
    children.append(G.entry("meter", PREFIX + "Meter", G.obj(("version", 1), ("handleName", "Data")), "%d %d %d %d" % METER,
                            "No", "Show", "Always", remap=[("Data", by("Meter").handle)]))
    for name, text, x, y in INDICATORS:
        dn = PREFIX + "Ind" + name.title().replace(" ", "")
        defs.append((dn, image_strip_def("ind", "%s_ind_%s.png" % (PREFIX, name.lower().replace(" ", "")), 2, IND_W, IND_H)))
        children.append(G.entry("ind " + name, dn, G.obj(("version", 1), ("handleName", "Data")), "%d %d %d %d" % (x, y, IND_W, IND_H),
                                "No", "Show", "Always", remap=[("Data", by(name).handle)]))
    # key LEDs
    for col, bit in lamps:
        defs.append(("%sLed%d_%d" % (PREFIX, col, bit), image_strip_def("led", lamp_file(col, bit), 256, LAMP_W, LAMP_H)))
    # keys
    for name, cap, x, row, w, face, lamp in KEYS:
        bx, by_, bw, bh = key_box(x, row, w)
        img = key_file(name)
        btn = G.entry("key", "Button", G.button_data(img, img, 1, 1), "0 0 %d %d" % (bw, bh), "No", "Show", "Always")
        dn = PREFIX + "Key" + img[len(PREFIX) + 5:-4].capitalize()
        defs.append((dn, fixed_component([btn])))
        children.append(G.entry(name, dn, G.obj(("version", 1), ("handleName", "Data")), "%d %d %d %d" % (bx, by_, bw, bh),
                                "No", "Show", "Always", remap=[("Data", by(name).handle)]))
        if lamp:
            children.append(G.entry("led " + name, "%sLed%d_%d" % (PREFIX, lamp[0], lamp[1]), G.obj(("version", 1), ("handleName", "Data")),
                                    "%d %d %d %d" % (bx + (bw - LAMP_W) // 2, by_ - 10, LAMP_W, LAMP_H), "No", "Show", "Always",
                                    remap=[("Data", by("LEDs %d" % lamp[0]).handle)]))
    # knobs and switches
    knob_children = [G.entry("focus", "Focus", G.focus_data(style["accent"]), "0 0 %d %d" % (KNOB, KNOB), "No", "Show", "WhenFocussed"),
                     G.entry("knob", "Knob", G.knob_filmstrip_data(PREFIX + "_knob.png", KNOB_FRAMES, "Vertical"), "0 0 %d %d" % (KNOB, KNOB),
                             "No", "Show", "Always")]
    defs.append((PREFIX + "Knob", fixed_component(knob_children, [G.action("Mouse Down", "Q-Link", "Data", "")])))
    sw = G.entry("switch", "Button", G.button_data(PREFIX + "_sw_on.png", PREFIX + "_sw_off.png", 1, 1), "0 0 %d %d" % (SWITCH, SWITCH),
                 "No", "Show", "Always")
    defs.append((PREFIX + "Switch", fixed_component([sw])))
    knob_boxes = []
    for name, cap, cx, kind in CONTROLS:
        p = by(name)
        if kind == "knob":
            box = (cx - KNOB // 2, KNOB_Y, KNOB, KNOB)
            knob_boxes.append(box)
            children.append(G.entry(name, PREFIX + "Knob", G.obj(("version", 1), ("handleName", "Data")), "%d %d %d %d" % box,
                                    "Yes", "Show", "Always", remap=[("Data", p.handle)]))
        else:
            children.append(G.entry(name, PREFIX + "Switch", G.obj(("version", 1), ("handleName", "Data")),
                                    "%d %d %d %d" % (cx - SWITCH // 2, KNOB_Y + (KNOB - SWITCH) // 2, SWITCH, SWITCH),
                                    "No", "Show", "Always", remap=[("Data", p.handle)]))
        children.append(G.entry(name + " value", "Label", G.label_data("Value", "ffd0d2d6", 18.0, "horizontallyCentred verticallyCentred"),
                                "%d %d 120 22" % (cx - 60, KNOB_Y + KNOB + 4), "No", "Show", "Always", remap=[("Data", p.handle)]))

    panel_tab = G.obj(("version", 1), ("tabName", "PANEL"), ("fnKeyIndex", 0), ("fnKeySubIndex", 0),
                      ("componentDefinition", G.component_definition([], children, "ff171718")),
                      ("qlinkBoundsData", []))      # the banks are not one block each on this panel

    # splice into the generated tree: our definitions, PANEL as the first tab
    page_data = dict(tui)["pageData"]
    pd = dict(page_data)
    pd["componentDefinitions"] = G.obj(*[(k, v) for k, v in pd["componentDefinitions"]])
    local = dict(pd["componentDefinitions"])["localComponentDefinitions"]
    local.extend(G.obj(("key", k), ("value", v)) for k, v in defs)
    tabs = pd["tabs"]
    for t in tabs:
        for i, (k, v) in enumerate(t):
            if k == "fnKeyIndex":
                t[i] = (k, v + 1)
    tabs.insert(0, panel_tab)
    new_pd = G.Obj([(k, pd[k]) if k == "tabs" else (k, v) for k, v in page_data])
    tui = G.obj(("pageData", new_pd))

    # Q-Links on PANEL. The Key 37 has one column of four knobs and banks through the 16 slots by
    # column (13, 9, 5, 1 then 14, 10, 6, 2 ...), so each column is one bank, read top to bottom:
    #   bank 1 levels: Input Level, Mixing, Volume, Headroom
    #   bank 2 filters: HP Freq, LP Freq, SEM Freq, SEM Res
    #   bank 3 SEM: SEM Mode, SEM Mix, SEM BP, Mono
    # Memory Select and Program are not on the knobs (the digits take the data wheel instead).
    q = G.build_qlinks(levels, params)
    screen = dict(q)["Screen Mode Q-Links"]
    entries = dict(screen)["map"]
    for e in entries:
        for i, (k, v) in enumerate(e):
            if k == "Tab":
                e[i] = (k, v + 1)
    banks = [["Input Level", "Mixing", "Volume", "Headroom"], ["HP Freq", "LP Freq", "SEM Freq", "SEM Res"], ["SEM Mode", "SEM Mix", "SEM BP", "Mono"]]
    qm = {}
    for c, bank in enumerate(banks):
        for r, n in enumerate(bank):
            qm[13 + c - 4 * r] = by(n).index
    qmap = G.Obj(("Q-Link %d" % n, qm.get(n, -1)) for n in range(1, 17))
    entries.insert(0, G.obj(("Tab", 1), ("SubTab", 1), ("Bank Direction", "Column"), ("Q-Links", qmap)))

    for img in sorted(G.referenced_images(tui, set())):
        src = os.path.join(kit_dir, img)
        if not os.path.isfile(os.path.join(OUT, img)) and os.path.isfile(src):
            shutil.copy2(src, os.path.join(OUT, img))
    with open(os.path.join(OUT, "TUI.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(G.dump_json(tui) + "\n")
    with open(os.path.join(OUT, "Q-Links.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(G.dump_json(q) + "\n")
    if os.path.isfile(os.path.join(OUT, "kit.json")):
        os.remove(os.path.join(OUT, "kit.json"))
    preview(os.path.join(HERE, "build", "panel-preview.png"))
    print("make_skin: wrote %s (%d files); preview in build/panel-preview.png" % (OUT, len(os.listdir(OUT))))


